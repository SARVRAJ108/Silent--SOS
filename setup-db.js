require("dotenv").config();

const pool = require("./db");

async function setupDatabase() {
    try {
        await pool.query(`
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                email VARCHAR(255) NOT NULL UNIQUE,
                mobile VARCHAR(20),
                password VARCHAR(255) NOT NULL,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
        `);

        await pool.query(`
    CREATE TABLE IF NOT EXISTS contacts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        name VARCHAR(100) NOT NULL,
        mobile VARCHAR(20),
        email VARCHAR(255),
        relationship VARCHAR(100),
        include_in_sos BOOLEAN DEFAULT TRUE,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
`);

await pool.query(`
    CREATE TABLE IF NOT EXISTS sos_alerts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        latitude DOUBLE PRECISION NOT NULL,
        longitude DOUBLE PRECISION NOT NULL,
        accuracy DOUBLE PRECISION,
        status VARCHAR(30) NOT NULL DEFAULT 'active',
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        resolved_at TIMESTAMPTZ
    );
`);

await pool.query(`
    CREATE TABLE IF NOT EXISTS location_updates (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        alert_id BIGINT REFERENCES sos_alerts(id) ON DELETE SET NULL,
        latitude DOUBLE PRECISION NOT NULL,
        longitude DOUBLE PRECISION NOT NULL,
        accuracy DOUBLE PRECISION,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
`);

await pool.query(`
    CREATE TABLE IF NOT EXISTS evidence (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL
            REFERENCES users(id) ON DELETE CASCADE,
        alert_id BIGINT
            REFERENCES sos_alerts(id) ON DELETE SET NULL,
        evidence_type VARCHAR(50) NOT NULL,
        file_path TEXT NOT NULL,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
`);

console.log("Evidence table created successfully!");

console.log("Location updates table created successfully!");

console.log("SOS alerts table created successfully!");

console.log("Contacts table created successfully!");

        console.log("Users table created successfully!");

    } catch (error) {
        console.error("Database setup failed:", error.message);
        process.exitCode = 1;
    } finally {
        await pool.end();
    }
}

setupDatabase();